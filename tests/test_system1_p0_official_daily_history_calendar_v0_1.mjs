import assert from "node:assert/strict";
import {dateOffset,taipeiNowParts,planOfficialSourceWindow} from "../ops/system1_p0_official_daily_history_calendar_v0_1.mjs";
assert.equal(dateOffset("2026-10-14",-14),"2026-09-30");
assert.deepEqual(taipeiNowParts("2026-10-14T08:10:00.000Z"),{day:"2026-10-14",hour:16,minute:10});
const weekdays=["2026-10-01","2026-10-02","2026-10-05","2026-10-06","2026-10-07","2026-10-08","2026-10-12","2026-10-13","2026-10-14"];
const result=planOfficialSourceWindow({now:"2026-10-14T08:10:00Z",officialTradingDates:weekdays});
assert.equal(result.target,"2026-10-14");
assert.equal(result.sourceStart,"2026-09-30");
assert.equal(result.tradingDates.length,9);
assert.equal(result.quoteDayNotInferredFromCron,true);
assert.throws(()=>planOfficialSourceWindow({now:"2026-10-14T06:00:00Z",officialTradingDates:weekdays}),/DAILY_OFFICIAL_NOT_AFTER_FINAL_SESSION/);
assert.throws(()=>planOfficialSourceWindow({now:"2026-10-14T08:10:00Z",officialTradingDates:[]}),/OFFICIAL_SESSION_CALENDAR_INVALID/);
assert.throws(()=>planOfficialSourceWindow({now:"2026-10-14T08:10:00Z",officialTradingDates:[...weekdays,weekdays.at(-1)]}),/OFFICIAL_SESSION_CALENDAR_INVALID/);
assert.throws(()=>planOfficialSourceWindow({now:"2026-10-14T08:10:00Z",officialTradingDates:["2026-11-01"]}),/OFFICIAL_SESSION_CALENDAR_INVALID/);
assert.throws(()=>planOfficialSourceWindow({now:"2026-10-14T08:10:00Z",officialTradingDates:["2026-09-11"]}),/OFFICIAL_SESSION_CALENDAR_INVALID/);
assert.throws(()=>planOfficialSourceWindow({now:"2026-10-14T08:10:00Z",officialTradingDates:["2026-10-01"]}),/LATEST_COMPLETED_OFFICIAL_SESSION_TOO_OLD/);
assert.throws(()=>dateOffset("2026-02-30",0),/INVALID_CALENDAR_DATE/);
const holiday=planOfficialSourceWindow({now:"2026-10-09T08:10:00Z",officialTradingDates:["2026-09-25","2026-10-06","2026-10-08"].filter(x=>x>="2026-09-25")});
assert.equal(holiday.target,"2026-10-08");
